"""Proving theorems by *locating* them, rather than by checking a proof.

The embedding's soundness argument runs in one direction only — from a position
in the space to a proof — which is exactly the direction a proof assistant wants.
This module makes that operational on a real corpus, in the one place it is
already decidable.

A statement is abstracted into a propositional formula over **atoms**: the
maximal subterms that are not themselves built from connectives. `(φ → ψ) → (φ →
ψ)` abstracts to `(A → B) → (A → B)`; `∀x φ → ∃x φ` abstracts to `A → B`, because
neither quantified formula is propositional structure this can see. Two
occurrences of the *same* subterm become the same atom, and "same" is exact
structural identity (`Arena.exact`) — never the alpha key, which identifies `ph`
with `ps` and would make `ph → ps` a tautology.

Then two certificates, both sound, neither consulting the proof:

* **Tautology.** If the abstraction is true under every assignment to its atoms,
  the statement is a substitution instance of a propositional tautology, and the
  corpus proves every one of those. In the embedding this is `E(φ) = +1` at
  *every* coordinate — φ is the top element of the Boolean algebra generated by
  its own atoms.
* **Library entailment.** Otherwise, gather the earlier premise-free theorems
  whose atoms the goal's atoms contain, and ask whether the goal is true under
  every assignment that makes all of them true. That is `E\\*(φ) = +1` in the
  embedding generated by those lemmas — the experiment's distinguished
  coordinate, with the lemmas as the generators. Since the corpus proves each
  lemma, it proves the goal.

The second subsumes the first (no lemmas needed is the empty-basis case) but they
are reported apart, because the gap between them is the only part that is *not*
a truth table — it is the library doing work.

One thing the truth tables below quietly assume. `wa`, `wo`, `wb`, `w3a`, `wxo`
and `wnan` are *defined* in set.mm rather than primitive, so giving each its
classical truth table implicitly leans on its defining theorem (`df-an`,
`df-xor`, …). Those are in the corpus and earlier than anything that uses them,
so no certificate is circular — but a certificate's real basis is its cited
lemmas *plus* the definitions of the connectives it contains.

What bounds coverage is matching, not the space. A lemma is usable here only when
its atoms occur in the goal *literally*, so `ax-1` stated over `ph, ps` is found
for a goal over `ph, ps` and missed for the same goal over `( ch → th )`. Real
retrieval would instantiate, which is what the fingerprint index exists to do;
this is the floor that gets, not the ceiling.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, Protocol

import numpy as np

if TYPE_CHECKING:
    from collections.abc import Sequence

    from experiments.lindenbaum.corpus import Theorem
    from experiments.lindenbaum.dag import Arena


class Store(Protocol):
    """What :func:`abstract` needs of a term store."""

    constructor: Sequence[str | None]
    children: Sequence[Sequence[int]]

    def identity(self, term: int) -> int: ...

#: set.mm's propositional connectives and their arities. A constructor absent
#: here — `wceq`, `wal`, `wral` — is opaque, and the subterm it heads becomes an
#: atom. Arity is checked against the term rather than trusted: a mismatch makes
#: the node an atom, which can only lose coverage, never soundness.
CONNECTIVES: dict[str, int] = {
    "wn": 1,
    "wi": 2,
    "wa": 2,
    "wo": 2,
    "wb": 2,
    "w3a": 3,
    "w3o": 3,
    "wxo": 2,
    "wnan": 2,
}

#: Above this many distinct atoms a truth table stops being the cheap option.
#: Nothing in set.mm's propositional statements comes close.
MAX_ATOMS = 16


@dataclass(frozen=True, slots=True)
class Formula:
    """A propositional abstraction: a connective tree over atom ids."""

    op: str
    args: tuple[Formula, ...] = ()
    atom: int = -1

    @property
    def is_atom(self) -> bool:
        return self.op == "atom"

    def atoms(self) -> frozenset[int]:
        if self.is_atom:
            return frozenset({self.atom})
        return frozenset().union(*(arg.atoms() for arg in self.args)) if self.args else frozenset()

    def connectives(self) -> int:
        return 0 if self.is_atom else 1 + sum(arg.connectives() for arg in self.args)

    def evaluate(self, values: dict[int, np.ndarray]) -> np.ndarray:
        if self.is_atom:
            return values[self.atom]
        parts = [arg.evaluate(values) for arg in self.args]
        if self.op == "wn":
            return ~parts[0]
        if self.op == "wi":
            return ~parts[0] | parts[1]
        if self.op == "wa":
            return parts[0] & parts[1]
        if self.op == "wo":
            return parts[0] | parts[1]
        if self.op == "wb":
            return parts[0] == parts[1]
        if self.op == "w3a":
            return parts[0] & parts[1] & parts[2]
        if self.op == "w3o":
            return parts[0] | parts[1] | parts[2]
        if self.op == "wxo":
            return parts[0] != parts[1]
        if self.op == "wnan":
            return ~(parts[0] & parts[1])
        raise ValueError(f"unknown connective {self.op!r}")


def abstract(store: Store, term: int, atoms: dict[int, int]) -> Formula:
    """Abstract a stored statement, interning atoms into ``atoms`` as it goes.

    ``store`` is anything that can name a term's constructor, its children, and
    its **exact structural identity** — both the read-only `Arena` and the
    prover's mutable `Terms` can, and the prover needs this over the terms it
    builds mid-search, not only over the ones the corpus stored.
    """
    constructor = store.constructor[term]
    arity = CONNECTIVES.get(constructor or "")
    if arity is not None and len(store.children[term]) == arity:
        return Formula(
            op=constructor or "",
            args=tuple(abstract(store, child, atoms) for child in store.children[term]),
        )
    return Formula(op="atom", atom=atoms.setdefault(store.identity(term), len(atoms)))


def entailed(goal: Formula, assumptions: Sequence[Formula]) -> bool:
    """Whether ``assumptions`` propositionally entail ``goal``.

    The Boolean algebra used as a *closer*: `E*(φ) = +1` in the algebra the
    assumptions generate. Sound for the same reason as everything in this module
    — the implication is a substitution instance of a tautology, and the corpus
    proves every one of those — and decidable by a truth table over the atoms
    the two sides share.
    """
    atoms = sorted(goal.atoms().union(*(a.atoms() for a in assumptions)) if assumptions else goal.atoms())
    if len(atoms) > MAX_ATOMS:
        return False
    values = _table(atoms)
    admissible = np.ones(1 << len(atoms), dtype=bool)
    for assumption in assumptions:
        admissible &= assumption.evaluate(values)
    return bool((goal.evaluate(values) | ~admissible).all())


def _table(atoms: Sequence[int]) -> dict[int, np.ndarray]:
    """Every assignment to ``atoms``, as one boolean column per atom."""
    rows = 1 << len(atoms)
    counter = np.arange(rows, dtype=np.int64)
    return {
        atom: ((counter >> position) & 1).astype(bool)
        for position, atom in enumerate(atoms)
    }


def is_tautology(formula: Formula) -> bool | None:
    """True/False, or None when the formula has more atoms than a table allows."""
    atoms = sorted(formula.atoms())
    if len(atoms) > MAX_ATOMS:
        return None
    return bool(formula.evaluate(_table(atoms)).all())


@dataclass(frozen=True, slots=True)
class Certificate:
    """Why a goal is provable, and on the strength of what."""

    label: str
    #: Labels of the library theorems the certificate rests on; empty for a
    #: tautology, which needs none.
    lemmas: tuple[str, ...]
    atoms: int
    connectives: int

    @property
    def tautology(self) -> bool:
        return not self.lemmas


@dataclass(frozen=True, slots=True)
class Lemma:
    label: str
    formula: Formula
    atoms: frozenset[int]


class Library:
    """The lemmas available to a certificate, indexed by their rarest atom.

    A lemma is usable for a goal only when the goal's atoms *contain* its own, so
    every usable lemma has its minimum atom among the goal's — which makes that
    minimum an exact index, not a heuristic filter. Without it the corpus is
    scanned once per goal, and the two together are 35 million subset tests.

    Mutable and append-only, because the interesting evaluation grows it: walking
    the corpus in declaration order, each theorem is a goal against everything
    before it and then becomes a lemma itself.
    """

    def __init__(self) -> None:
        self._by_least_atom: dict[int, list[Lemma]] = {}
        self.size = 0

    def add(self, lemma: Lemma) -> None:
        self._by_least_atom.setdefault(min(lemma.atoms), []).append(lemma)
        self.size += 1

    def usable(self, atoms: frozenset[int]) -> list[Lemma]:
        found: list[Lemma] = []
        for atom in atoms:
            for lemma in self._by_least_atom.get(atom, ()):
                if lemma.atoms <= atoms:
                    found.append(lemma)
        return found


def certify(
    goal: Formula, label: str, library: Library, *, cap: int = 64
) -> Certificate | None:
    """A certificate for ``goal``, or None if this fragment cannot reach it."""
    goal_atoms = sorted(goal.atoms())
    if len(goal_atoms) > MAX_ATOMS:
        return None
    values = _table(goal_atoms)
    truth = goal.evaluate(values)
    if truth.all():
        return Certificate(label, (), len(goal_atoms), goal.connectives())

    # Richest lemmas first: one mentioning more of the goal's atoms constrains
    # more assignments, so the cap costs less when it binds.
    usable = sorted(
        library.usable(frozenset(goal_atoms)),
        key=lambda lemma: -len(lemma.atoms),
    )[:cap]
    if not usable:
        return None

    admissible = np.ones(len(truth), dtype=bool)
    for lemma in usable:
        admissible &= lemma.formula.evaluate(values)
        if not admissible.any():
            # No assignment satisfies the lemmas: the basis is propositionally
            # inconsistent, which would certify anything. That never happens for
            # a consistent corpus, and if it did the certificate would be
            # worthless — so refuse rather than report a vacuous success.
            return None
    if not bool((truth | ~admissible).all()):
        return None
    # Report only the lemmas that were needed, smallest basis first.
    needed: list[Lemma] = []
    admissible = np.ones(len(truth), dtype=bool)
    for lemma in usable:
        if bool((truth | ~admissible).all()):
            break
        admissible &= lemma.formula.evaluate(values)
        needed.append(lemma)
    return Certificate(
        label,
        tuple(lemma.label for lemma in needed),
        len(goal_atoms),
        goal.connectives(),
    )


def as_lemma(arena: Arena, theorem: Theorem, atoms: dict[int, int]) -> Lemma | None:
    """A theorem as a citable lemma, or None if it cannot be one.

    A theorem with hypotheses is refused for the same reason it cannot be a
    generator: it asserts a rule, not its conclusion. One whose abstraction is a
    bare atom carries no propositional content and would only slow the search.
    """
    if theorem.premises or theorem.term < 0:
        return None
    formula = abstract(arena, theorem.term, atoms)
    if formula.is_atom:
        return None
    return Lemma(label=theorem.label, formula=formula, atoms=formula.atoms())


def build_library(
    arena: Arena, theorems: Sequence[Theorem], atoms: dict[int, int]
) -> Library:
    library = Library()
    for theorem in theorems:
        lemma = as_lemma(arena, theorem, atoms)
        if lemma is not None:
            library.add(lemma)
    return library
